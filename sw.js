// App-Shell-Caching für vollständige Offline-Nutzung.
// WICHTIG: CACHE_NAME bei JEDEM Deploy hochzählen, sonst bekommen bereits
// installierte Geräte Updates nicht mit (siehe README).
const CACHE_NAME = 'aufmass-gaeb-v4';

const APP_SHELL = [
  './',
  './index.html',
  './app.js',
  './db.js',
  './gaebCommon.js',
  './gaebLvParser.js',
  './gaebX31.js',
  './styles.css',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/apple-touch-icon.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((response) => {
          if (response.ok) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        })
        .catch(() => cached);
    })
  );
});
